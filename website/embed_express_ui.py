#!/usr/bin/env python3
"""Embed the planetCompute program's page (client/ui/index.html) and its example picture and video prompts into the website Worker
for Express mode (planetcompute.ai/express/local/). Run before every deploy that should carry a newer program page:
    python3 embed_express_ui.py            (from BrowserCFWorkerCode/; edits worker.live.js and worker.js)
Writes between the lines '// EXPRESS_UI_BEGIN' and '// EXPRESS_UI_END'."""
import base64, json, pathlib, re, sys
here = pathlib.Path(__file__).resolve().parent
ui = here.parent / "planetCompute-CPP" / "client" / "ui"
page = (ui / "index.html").read_bytes()
prompts = {k: [l.strip() for l in (ui / f"{k}_prompts.txt").read_text(encoding="utf-8").splitlines() if l.strip()][:100]
           for k in ("image", "video")}
block = ("// EXPRESS_UI_BEGIN (generated by embed_express_ui.py from planetCompute-CPP/client/ui: do not edit by hand)\n"
         f"const EXPRESS_UI_B64 = \"{base64.b64encode(page).decode()}\";\n"
         f"const EXPRESS_PROMPTS = {json.dumps(prompts, ensure_ascii=False)};\n"
         "// EXPRESS_UI_END")
for name in sys.argv[1:] or ["worker.live.js", "worker.js"]:
    p = here / name; s = p.read_text(encoding="utf-8")
    new, n = re.subn(r"// EXPRESS_UI_BEGIN.*?// EXPRESS_UI_END", lambda m: block, s, count=1, flags=re.S)
    if n != 1: sys.exit(f"{name}: markers not found")
    p.write_text(new, encoding="utf-8"); print(f"{name}: embedded the program page ({len(page):,} bytes) and {len(prompts['image'])} picture + {len(prompts['video'])} video prompts")
